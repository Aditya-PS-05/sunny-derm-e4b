@Composable
fun translated(text: String): String {
    val language = currentSunnyLanguage()
    var value by remember(language, text) {
        mutableStateOf(cachedTranslation(language, text))
    }
    LaunchedEffect(language, text) {
        value = cachedTranslation(language, text)
        if (value == null) {
            value = runCatching { translateWithMlKit(language, text) }.getOrNull()
        }
    }
    return value ?: translationPlaceholder(text)
}
